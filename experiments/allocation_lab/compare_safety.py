"""Offline A/C durable-resume and priority comparison; only fictional stdout.

For real saved data, require explicit output outside repository. No actual
identity labels, API responses or progress truth are generated by this lab.
"""
import argparse,json,socket,tempfile,time
from pathlib import Path
from datetime import timedelta
from unittest.mock import patch
from .allocation import native,cost_profile,opportunities,simulate,dt
from .run import fictional
from .snapshot import adapt,read,pair_catalogue
from .priority import POLICIES,signals
from .session import Session


def compare(jobs,other,seed,asof,last,profiles,catalogue=()):
    windows=opportunities(asof,last);results=[];started=time.perf_counter()
    with tempfile.TemporaryDirectory(prefix='safety-sessions-') as directory:
        for mode in ('estimated_settlement','reservation_only'):
            for plan in ('A','C'):
                for policy in POLICIES:
                    path=Path(directory)/(mode+'-'+plan+'-'+policy+'.sqlite')
                    for index,window in enumerate(windows):
                        session=Session(path)
                        result=session.apply('window-'+str(index),plan,jobs,seed,[window],profiles,catalogue=catalogue,
                                             other_versions=other,asof=asof,priority_policy=policy,cost_mode=mode)
                        # Simulated process exit and restart before every window.
                        retry=session.apply('window-'+str(index),plan,jobs,seed,[window],profiles,catalogue=catalogue,
                                            other_versions=other,asof=asof,priority_policy=policy,cost_mode=mode)
                        if retry!=result:raise AssertionError('duplicate operation changed results')
                        manifest_count=len(session.records());catalogue_count=session.db.execute('SELECT count(*) FROM catalogue').fetchone()[0];session.close()
                    direct=simulate(plan,jobs,seed,windows,profiles,other_versions=other,asof=asof,priority_policy=policy,cost_mode=mode)
                    if result!=direct:raise AssertionError('resumed result differs')
                    results.append({'plan':plan,'policy':policy,'cost_mode':mode,'manifest_count':manifest_count,'catalogue_count':catalogue_count,'result':result})
    outcomes=[]
    for plan in ('A','C'):
        for policy in POLICIES:
            for outcome in ('unknown','mock_downstream'):
                r=simulate(plan,jobs,seed,windows,profiles,other_versions=other,asof=asof,priority_policy=policy,outcome=outcome)
                outcomes.append({k:r[k] for k in ('plan','priority_policy','outcome','completed_actual_groups','completed_mock_groups','transferred_mock_article_versions','final_waiting_article_versions')})
    return {'outcome_comparison':outcomes,'data_kind':'caller_defined','results':results,'elapsed_seconds':time.perf_counter()-started,'actual_completions':0,'real_API_calls':0,'external_news_fetches':0,'identity_accuracy':'unconfirmed'}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--snapshot',type=Path);p.add_argument('--profiles',type=Path);p.add_argument('--private-output',type=Path);a=p.parse_args()
    if a.snapshot:
        if not a.profiles or not a.private_output:p.error('snapshot requires profiles and private-output')
        if a.private_output.resolve().is_relative_to(Path(__file__).resolve().parents[2]) or a.private_output.resolve().is_relative_to(a.snapshot.resolve()):p.error('output must stay outside repository and snapshot')
    elif a.profiles or a.private_output:p.error('private arguments require snapshot')
    with patch.object(socket.socket,'connect',side_effect=AssertionError('network forbidden')),patch.object(socket,'create_connection',side_effect=AssertionError('network forbidden')),patch.object(native,'response',side_effect=AssertionError('API forbidden')):
        if a.snapshot:
            profiles=cost_profile(json.loads(a.profiles.read_text())['profiles']);jobs,other,health=adapt(a.snapshot,profiles);seed=read(a.snapshot,'ai_budget');asof=health['updated_at'];last=seed['last_ai_run_at'];catalogue=pair_catalogue(a.snapshot)
            _,schedules=signals(read(a.snapshot,'status_pending'),read(a.snapshot,'events'),dt(asof))
        else:
            jobs,other,seed,asof,last,profiles=fictional();catalogue=[];schedules=[]
            for i,j in enumerate(jobs['status']):j.update(followup_candidate=i%7==0,progress_candidate=i%9==0,due_related_candidate=i%19==0)
        output=compare(jobs,other,seed,asof,last,profiles,catalogue);output['data_kind']='private_saved_snapshot' if a.snapshot else 'fictional_only'
        output['schedules']=schedules;output['candidate_counts']={k:sum(bool(j.get(k)) for j in jobs['status']) for k in ('followup_candidate','progress_candidate','due_related_candidate')}
        output['candidate_counts']['long_wait_48h']=sum(bool(j.get('first_seen_at')) and dt(asof)-dt(j['first_seen_at'])>=timedelta(hours=48) for j in jobs['status'])
        output['candidate_counts']['ordinary_without_retrieval_signal']=sum(not any(j.get(k) for k in ('followup_candidate','progress_candidate','due_related_candidate')) for j in jobs['status'])
        output['candidate_counts']['saved_url_relation_only_not_identity']=sum(any(m['same_saved_url'] for m in j.get('retrieval_matches',[])) for j in jobs['status'])
        output['pair_catalogue_counts']={'all_possible':len(catalogue),'native_selected':sum(x['native_retrieval_selected'] for x in catalogue),'common_keyword_outside_selected':sum(x['has_common_native_keyword'] and not x['native_retrieval_selected'] for x in catalogue)}
    if a.snapshot:a.private_output.write_text(json.dumps(output,ensure_ascii=False,indent=2));print('Private comparison saved outside repository; no source records changed.')
    else:print(json.dumps(output,ensure_ascii=False,indent=2))

if __name__=='__main__':main()
